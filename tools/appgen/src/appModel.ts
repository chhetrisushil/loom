import * as fs from "node:fs";
import * as path from "node:path";
import ts from "typescript";
import { isStubBody } from "./stub";

// ── AppModel: a compact, deterministic summary of an existing Loom app ────────
//
// Stage 1 of the AI-native appgen pipeline. `scanApp` walks the folder convention
// (`app/flows/<id>/flow.ts`) and produces a small structured model of what already
// exists — never raw file contents. Brownfield "intelligence" comes from this
// deterministic scan; the model (Stage 2) only ever reasons over this summary, which
// keeps its context (and memory footprint) tiny. A net-new project yields an
// AppModel with `flows: []`.

/** Whether a step's handler is an untouched generated stub, hand-edited, or external
 * (a `toolId` step, or one with no `handler$` at all — e.g. a human/suspend step). */
export type HandlerState = "stub" | "edited" | "external";

export interface StepModel {
  id: string;
  handlerState: HandlerState;
}

export interface FlowModel {
  id: string;
  /** Path relative to the scanned root, e.g. `app/flows/planner/flow.ts`. */
  file: string;
  steps: StepModel[];
  /** The runner contains a `ctx.suspend(` approval/human gate. */
  hasApproval: boolean;
  /** The runner writes a UI surface via `surface(ctx).set(` (or the legacy `ctx.ui.set(`). */
  hasUi: boolean;
  /** The file still carries the `// Generated by @loom/appgen` marker header. */
  isGenerated: boolean;
}

export interface AppModel {
  root: string;
  /** True if `root` looks like an existing Loom app (folder-convention markers). */
  isExisting: boolean;
  flows: FlowModel[];
  /**
   * Root-relative paths the scan REFUSED to follow because they are symbolic links (`app`,
   * `app/flows`, a flow folder, or a `flow.ts`). A link is not an in-project source: it can point
   * anywhere, so the scan neither reads through it nor offers it as a flow to edit.
   */
  skippedLinks?: string[];
}

/** The folder-convention markers that identify an existing Loom app under `root`. */
export function isExistingApp(root: string): boolean {
  return (
    fs.existsSync(path.join(root, "package.json")) ||
    fs.existsSync(path.join(root, "app", "loom.gen.ts")) ||
    fs.existsSync(path.join(root, "app", "config.ts"))
  );
}

/**
 * Scan a project root into an {@link AppModel}. Pure and deterministic — reads the
 * filesystem and parses each `flow.ts` with the TypeScript AST, but calls no model and
 * writes nothing. A missing `app/flows` directory (net-new) yields `flows: []`.
 */
export function scanApp(root: string): AppModel {
  const appDir = path.join(root, "app");
  const flowsDir = path.join(appDir, "flows");
  const flows: FlowModel[] = [];
  const skippedLinks: string[] = [];
  const isLink = (p: string): boolean => {
    try {
      return fs.lstatSync(p).isSymbolicLink();
    } catch {
      return false;
    }
  };
  if (isLink(appDir)) {
    skippedLinks.push("app");
  } else if (isLink(flowsDir)) {
    skippedLinks.push(path.join("app", "flows"));
  } else if (fs.existsSync(flowsDir)) {
    const all = fs.readdirSync(flowsDir, { withFileTypes: true });
    // `Dirent` is lstat-based: a symlinked flow folder is not `isDirectory()`; record it instead of
    // dropping it silently.
    for (const e of all) {
      if (e.isSymbolicLink()) skippedLinks.push(path.join("app", "flows", e.name));
    }
    const entries = all.filter((e) => e.isDirectory()).sort((a, b) => a.name.localeCompare(b.name));
    for (const entry of entries) {
      for (const ext of ["ts", "tsx"]) {
        const abs = path.join(flowsDir, entry.name, `flow.${ext}`);
        const rel = path.join("app", "flows", entry.name, `flow.${ext}`);
        if (isLink(abs)) {
          skippedLinks.push(rel);
          break;
        }
        if (fs.existsSync(abs)) {
          flows.push(scanFlowFile(abs, rel, entry.name));
          break;
        }
      }
    }
  }
  return {
    root,
    isExisting: isExistingApp(root),
    flows,
    ...(skippedLinks.length > 0 && { skippedLinks }),
  };
}

function scanFlowFile(abs: string, rel: string, folderId: string): FlowModel {
  const src = fs.readFileSync(abs, "utf8");
  // setParentNodes = true so `.getText()` works on nested nodes.
  const sf = ts.createSourceFile(abs, src, ts.ScriptTarget.Latest, true);

  let flowId = folderId;
  const steps: StepModel[] = [];

  const visit = (node: ts.Node): void => {
    if (
      ts.isCallExpression(node) &&
      ts.isObjectLiteralExpression(node.arguments[0] ?? ({} as ts.Node))
    ) {
      const callee = node.expression.getText(sf);
      const obj = node.arguments[0] as ts.ObjectLiteralExpression;
      if (callee === "step$") {
        steps.push(scanStep(obj, sf));
      } else if (callee === "flow$") {
        const id = stringProp(obj, "id", sf);
        if (id !== undefined) flowId = id;
      }
    }
    ts.forEachChild(node, visit);
  };
  visit(sf);

  return {
    id: flowId,
    file: rel,
    steps,
    hasApproval: /ctx\.suspend\s*\(/.test(src),
    hasUi: /(?:ctx\.ui|surface\s*\(\s*ctx\s*\))\.set\s*\(/.test(src),
    isGenerated: src.startsWith("// Generated by @loom/appgen"),
  };
}

function scanStep(obj: ts.ObjectLiteralExpression, sf: ts.SourceFile): StepModel {
  const id = stringProp(obj, "id", sf) ?? "";
  const handler = propInit(obj, "handler");
  let handlerState: HandlerState = "external";
  if (
    handler !== undefined &&
    ts.isCallExpression(handler) &&
    handler.expression.getText(sf) === "handler$" &&
    handler.arguments[0] !== undefined
  ) {
    handlerState = isStubBody(id, handler.arguments[0].getText(sf)) ? "stub" : "edited";
  }
  return { id, handlerState };
}

function propInit(obj: ts.ObjectLiteralExpression, name: string): ts.Expression | undefined {
  for (const p of obj.properties) {
    if (ts.isPropertyAssignment(p) && p.name.getText() === name) return p.initializer;
  }
  return undefined;
}

function stringProp(
  obj: ts.ObjectLiteralExpression,
  name: string,
  _sf: ts.SourceFile
): string | undefined {
  const init = propInit(obj, name);
  return init !== undefined && ts.isStringLiteralLike(init) ? init.text : undefined;
}
