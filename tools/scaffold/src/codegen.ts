/** kebab/snake/space → PascalCase, for deriving export names. */
export function pascal(name: string): string {
  return name
    .split(/[-_\s]+/)
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join("");
}

/** kebab/snake/space → camelCase, for deriving a valid function identifier. */
export function camel(name: string): string {
  const p = pascal(name);
  return p.charAt(0).toLowerCase() + p.slice(1);
}

/**
 * Generate the text of `loom.gen.ts` — a static module that imports each flow
 * module and re-exports them as `flowModules`, for `defineConfig({ flowModules })`.
 *
 * This is the replay-safe form of "auto-wire from the filesystem": the imports are
 * STATIC (fixed at build time by `loom gen`), so the set of flows is identical on
 * every resume / remote worker. `importPaths` are module specifiers relative to
 * the generated file (extension-less), e.g. `./flows/greet/flow`.
 */
export function generateRegistration(importPaths: string[]): string {
  const imports = importPaths.map((p, i) => `import * as _f${i} from "${p}";`);
  const refs = importPaths.map((_, i) => `_f${i}`).join(", ");
  return [
    "// AUTO-GENERATED by `loom gen`. Do not edit by hand.",
    "// Statically-imported flow modules for defineConfig({ flowModules }).",
    ...imports,
    "",
    `export const flowModules = [${refs}];`,
    "",
  ].join("\n");
}
