/** kebab/snake/space → PascalCase, for deriving export names. */
export function pascal(name: string): string {
  return name
    .split(/[-_\s]+/)
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join("");
}

/** kebab/snake/space → camelCase, for deriving a valid function identifier. */
export function camel(name: string): string {
  const p = pascal(name);
  return p.charAt(0).toLowerCase() + p.slice(1);
}

/**
 * Generate the text of `loom.gen.ts` — a static module that imports the discovered
 * flow / agent / tool / skill modules and re-exports them as `flowModules` /
 * `agentModules` / `toolModules` / `skillModules`, for
 * `defineConfig({ flowModules, agentModules, toolModules, skillModules })`.
 *
 * This is the replay-safe form of "auto-wire from the filesystem": the imports are
 * STATIC (fixed at build time by `loom gen`), so the set is identical on every
 * resume / remote worker. Each `*Paths` is module specifiers relative to the
 * generated file (extension-less), e.g. `./flows/greet/flow`, `./agents/triage`.
 */
export function generateRegistration(
  flowPaths: string[],
  agentPaths: string[] = [],
  toolPaths: string[] = [],
  skillPaths: string[] = []
): string {
  const group = (paths: string[], prefix: string, exportName: string): string[] => {
    const imports = paths.map((p, i) => `import * as ${prefix}${i} from "${p}";`);
    const refs = paths.map((_, i) => `${prefix}${i}`).join(", ");
    return [...imports, "", `export const ${exportName} = [${refs}];`, ""];
  };
  return [
    "// AUTO-GENERATED by `loom gen`. Do not edit by hand.",
    "// Static modules for defineConfig({ flowModules, agentModules, toolModules, skillModules }).",
    ...group(flowPaths, "_f", "flowModules"),
    ...group(agentPaths, "_a", "agentModules"),
    ...group(toolPaths, "_t", "toolModules"),
    ...group(skillPaths, "_s", "skillModules"),
  ].join("\n");
}
