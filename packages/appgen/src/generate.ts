import type { AppSpec, CapabilitySpec, GeneratedFile } from "./types";

function pascal(id: string): string {
  return id.replace(/(^|-)([a-z0-9])/g, (_m, _p, c: string) => c.toUpperCase());
}
function camel(id: string): string {
  const p = pascal(id);
  return p.charAt(0).toLowerCase() + p.slice(1);
}

// Emit one capability's flow as plain, static, inspectable TypeScript. Reasoning /
// approval / UI are only wired when the spec asks for them, and every model call,
// approval gate, and UI update is ordinary Loom code the developer owns and edits.
function generateCapabilityFile(cap: CapabilitySpec): GeneratedFile {
  const Name = pascal(cap.id);
  const stepConsts = cap.steps.map((s) => `${camel(s)}Step`);
  const usesReasoning = cap.reasoning !== undefined;

  const imports = [
    `import { capability$ } from "@loom/capability";`,
    `import { flow$, handler$, step$ } from "@loom/core";`,
    `import type { FlowRunner, RegisteredFlow } from "@loom/workflow-runtime";`,
    `import { z } from "zod";`,
    // A commented hint (not a live import) so the generated file has no unused symbol.
    ...(usesReasoning ? [`// import { ReasoningRuntime } from "@loom/reasoning";`] : []),
  ].join("\n");

  const steps = cap.steps
    .map(
      (s) => `const ${camel(s)}Step = step$({
  id: "${s}",
  name: "${pascal(s)}",
  inputSchema: z.object({ prompt: z.string() }),
  outputSchema: z.object({ result: z.string() }),
  handler: handler$(async (input) => ({ result: \`TODO: implement ${s} for \${input.prompt}\` })),
});`
    )
    .join("\n\n");

  const runnerBody: string[] = [];
  if (usesReasoning) {
    const base = cap.reasoning?.baseModel ?? "the base model";
    const ladder = [cap.reasoning?.baseModel, ...(cap.reasoning?.elevateTo ?? [])]
      .filter((m): m is string => m !== undefined)
      .join(" → ");
    runnerBody.push(
      `  // Reasoning: route via ${base} first${
        cap.reasoning?.elevateTo?.length ? `, elevate to ${cap.reasoning.elevateTo.join(", ")}` : ""
      } (${ladder}).`,
      `  // Wire providers into a ReasoningRuntime and pass ctx.decide so the route is logged (P9):`,
      `  //   const { content } = await reasoning.reason(`,
      `  //     { messages: [{ role: "user", content: input.prompt }], strategy: "${cap.id}" },`,
      `  //     { decide: ctx.decide },`,
      `  //   );`
    );
  }
  runnerBody.push(`  const out = await ctx.run(${stepConsts[0]}, { prompt: input.prompt });`);
  if (cap.approval === true) {
    runnerBody.push(
      `  // Pause for a human approval — a durable suspend gate; resume with { eventType: "Approved" }.`,
      `  await ctx.suspend({ on: "Approved" });`
    );
  }
  if (cap.ui === true) {
    runnerBody.push(`  ctx.ui.set("status", "done"); // durable, replayable UI surface`);
  }
  runnerBody.push(`  return out;`);

  const contents = `// Generated by @loom/appgen from intent: "${cap.intent}"
// Plain, static TypeScript — yours to own and edit. Statically wired (P5).
${imports}

${steps}

const ${camel(cap.id)}Runner: FlowRunner<{ prompt: string }, { result: string }> = async (ctx, input) => {
${runnerBody.join("\n")}
};

export const ${camel(cap.id)}Flow: RegisteredFlow<{ prompt: string }, { result: string }> = {
  definition: flow$({
    id: "${cap.id}",
    name: "${Name}",
    version: "1.0.0",
    inputSchema: z.object({ prompt: z.string() }),
    outputSchema: z.object({ result: z.string() }),
    steps: [${stepConsts.join(", ")}],
  }),
  runner: ${camel(cap.id)}Runner,
};

export const ${camel(cap.id)}Capability = capability$({
  id: "${cap.id}",
  intent: ${JSON.stringify(cap.intent)},
  inputSchema: z.object({ prompt: z.string() }),
  flow: ${camel(cap.id)}Flow,
});
`;

  return { path: `src/${cap.id}.ts`, contents };
}

// Emit the app composition root (defineConfig) registering every capability.
function generateAppFile(spec: AppSpec): GeneratedFile {
  const caps = spec.capabilities;
  const imports = caps
    .map((c) => `import { ${camel(c.id)}Capability } from "./${c.id}";`)
    .join("\n");
  const registrations = caps.map((c) => `.register(${camel(c.id)}Capability)`).join("");
  const computeNote =
    spec.compute?.target !== undefined
      ? `\n// Compute target: ${spec.compute.target}. For production, place executions with a\n// PlacementDispatcher over a ${spec.compute.target} WorkerRuntime (see @loom/dispatcher).\n`
      : "";

  const contents = `// Generated by @loom/appgen — the composition root (edit freely).
import { defineConfig } from "@loom/app";
import { CapabilityCatalog } from "@loom/capability";
${imports}

const catalog = new CapabilityCatalog()${registrations};

export const app = defineConfig({
  storage: { kind: "memory" },
  catalog,
});
${computeNote}`;

  return { path: "src/app.ts", contents };
}

/**
 * Generate a Loom app skeleton from an {@link AppSpec}: one file per capability plus a
 * `defineConfig` composition root. Returns file contents as strings — a pure function,
 * so the caller (a CLI, an editor) decides where to write them. The output is ordinary,
 * inspectable Loom TypeScript with TODO handlers to fill in.
 */
export function generateApp(spec: AppSpec): GeneratedFile[] {
  return [...spec.capabilities.map(generateCapabilityFile), generateAppFile(spec)];
}
