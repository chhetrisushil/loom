import { appFiles, generateRegistration, pascal } from "@loom/scaffold";
import type { AppSpec, CapabilitySpec, GeneratedFile } from "./types";

function camel(id: string): string {
  const p = pascal(id);
  return p.charAt(0).toLowerCase() + p.slice(1);
}

// Emit one capability's flow as plain, static, inspectable TypeScript at the folder
// convention path `app/flows/<id>/flow.ts` (discovered by `loom gen`, wired via
// `flowModules`). Reasoning / approval / UI are only wired when the spec asks for
// them, and every model call, approval gate, and UI update is ordinary Loom code the
// developer owns and edits.
function generateFlowFile(cap: CapabilitySpec): GeneratedFile {
  const Name = pascal(cap.id);
  const stepConsts = cap.steps.map((s) => `${camel(s)}Step`);
  const usesReasoning = cap.reasoning !== undefined;

  const imports = [
    `import { flow$, handler$, step$ } from "@loom/core";`,
    `import type { FlowRunner, RegisteredFlow } from "@loom/workflow-runtime";`,
    `import { z } from "zod";`,
    // A commented hint (not a live import) so the generated file has no unused symbol.
    ...(usesReasoning ? [`// import { ReasoningRuntime } from "@loom/reasoning";`] : []),
  ].join("\n");

  const steps = cap.steps
    .map(
      (s) => `const ${camel(s)}Step = step$({
  id: "${s}",
  name: "${pascal(s)}",
  inputSchema: z.object({ prompt: z.string() }),
  outputSchema: z.object({ result: z.string() }),
  handler: handler$(async (input: { prompt: string }) => ({ result: \`TODO: implement ${s} for \${input.prompt}\` })),
});`
    )
    .join("\n\n");

  const runnerBody: string[] = [];
  if (usesReasoning) {
    const base = cap.reasoning?.baseModel ?? "the base model";
    const ladder = [cap.reasoning?.baseModel, ...(cap.reasoning?.elevateTo ?? [])]
      .filter((m): m is string => m !== undefined)
      .join(" → ");
    runnerBody.push(
      `  // Reasoning: route via ${base} first${
        cap.reasoning?.elevateTo?.length ? `, elevate to ${cap.reasoning.elevateTo.join(", ")}` : ""
      } (${ladder}).`,
      "  // Wire providers into a ReasoningRuntime and pass ctx.decide so the route is logged (P9):",
      "  //   const { content } = await reasoning.reason(",
      `  //     { messages: [{ role: "user", content: input.prompt }], strategy: "${cap.id}" },`,
      "  //     { decide: ctx.decide },",
      "  //   );"
    );
  }
  runnerBody.push(`  const out = await ctx.run(${stepConsts[0]}, { prompt: input.prompt });`);
  if (cap.approval === true) {
    runnerBody.push(
      `  // Pause for a human approval — a durable suspend gate; resume with { eventType: "Approved" }.`,
      `  await ctx.suspend({ on: "Approved" });`
    );
  }
  if (cap.ui === true) {
    runnerBody.push(`  ctx.ui.set("status", "done"); // durable, replayable UI surface`);
  }
  runnerBody.push("  return out;");

  const contents = `// Generated by @loom/appgen from intent: "${cap.intent}"
// Plain, static TypeScript — yours to own and edit. Statically wired (P5).
${imports}

${steps}

const ${camel(cap.id)}Runner: FlowRunner<{ prompt: string }, { result: string }> = async (ctx, input) => {
${runnerBody.join("\n")}
};

export const ${Name}Flow: RegisteredFlow<{ prompt: string }, { result: string }> = {
  definition: flow$({
    id: "${cap.id}",
    name: "${Name}",
    version: "1.0.0",
    inputSchema: z.object({ prompt: z.string() }),
    outputSchema: z.object({ result: z.string() }),
    steps: [${stepConsts.join(", ")}],
  }),
  runner: ${camel(cap.id)}Runner,
};
`;

  return { path: `app/flows/${cap.id}/flow.ts`, contents };
}

// The app entry point, targeting the first capability. When that capability pauses
// for approval, the entry drives the suspend → resume round-trip so `pnpm start`
// runs to completion instead of hanging at the gate.
function generateMainFile(spec: AppSpec): string {
  const first = spec.capabilities[0];
  if (first === undefined) throw new Error("appgen: spec has no capabilities");
  const Name = pascal(first.id);
  const head = [
    `import { app } from "./config";`,
    `import { ${Name}Flow } from "./flows/${first.id}/flow";`,
    "",
  ];

  if (first.approval === true) {
    return [
      ...head,
      "async function main() {",
      `  const handle = await app.runtime.start(${Name}Flow, { prompt: "hello" });`,
      "  const suspended = await handle.waitForSuspend();",
      "  console.log(`⏸  suspended at #${suspended.sequence}`);",
      `  const resumed = await app.runtime.resume(handle.executionId, { eventType: "Approved", payload: {} });`,
      "  const done = await resumed.waitForCompletion();",
      "  console.log(`✅ ${done.status}`);",
      "  await app.close();",
      "}",
      "",
      "void main();",
      "",
    ].join("\n");
  }

  return [
    ...head,
    "async function main() {",
    `  const handle = await app.runtime.start(${Name}Flow, { prompt: "hello" });`,
    "  const state = await handle.waitForCompletion();",
    "  console.log(state.variables._output);",
    "  await app.close();",
    "}",
    "",
    "void main();",
    "",
  ].join("\n");
}

// A non-hanging smoke test: assert the first flow is registered and statically wired.
// (A full end-to-end run belongs in the developer's own tests / `loom eval`.)
function generateTestFile(spec: AppSpec): GeneratedFile {
  const first = spec.capabilities[0];
  if (first === undefined) throw new Error("appgen: spec has no capabilities");
  const Name = pascal(first.id);
  const contents = [
    `import { describe, expect, it } from "vitest";`,
    `import { ${Name}Flow } from "./flows/${first.id}/flow";`,
    `import { flowModules } from "./loom.gen";`,
    "",
    `describe("${first.id}", () => {`,
    `  it("is registered and statically wired", () => {`,
    `    expect(${Name}Flow.definition.id).toBe("${first.id}");`,
    "    expect(flowModules.length).toBeGreaterThan(0);",
    "  });",
    "});",
    "",
  ].join("\n");
  return { path: `app/${first.id}.test.ts`, contents };
}

/**
 * Generate just the folder-convention flow files (`app/flows/<id>/flow.ts`) for a
 * spec — one per capability. Used when scaffolding into an EXISTING Loom app: the
 * caller writes these, then regenerates `app/loom.gen.ts` from the filesystem
 * (`loom gen`) so pre-existing flows stay wired.
 */
export function generateFlows(spec: AppSpec): GeneratedFile[] {
  return spec.capabilities.map(generateFlowFile);
}

/**
 * Generate a complete, runnable Loom project from an {@link AppSpec}, following the
 * folder convention (the same shape `create-loom-app` emits): `package.json`,
 * `tsconfig.json`, `app/config.ts`, `app/main.ts`, `app/loom.gen.ts`, and one
 * `app/flows/<id>/flow.ts` per capability. Seeded from the NL intent; `pnpm install
 * && pnpm start` runs out of the box. A pure function — the caller decides where to
 * write the files.
 */
export function generateProject(spec: AppSpec): GeneratedFile[] {
  // Start from the scaffold baseline, minus its sample greet flow + test (we splice
  // in the NL-derived flows below).
  const sample = new Set(["app/flows/greet/flow.ts", "app/greet.test.ts"]);
  const files: Record<string, string> = {};
  for (const [path, contents] of Object.entries(appFiles(spec.name))) {
    if (!sample.has(path)) files[path] = contents;
  }

  // Splice in the NL-derived flows and regenerate registration over exactly them.
  for (const f of generateFlows(spec)) files[f.path] = f.contents;
  files["app/loom.gen.ts"] = generateRegistration(
    spec.capabilities.map((c) => `./flows/${c.id}/flow`)
  );

  // Entry point + smoke test targeting the first capability.
  files["app/main.ts"] = generateMainFile(spec);
  const test = generateTestFile(spec);
  files[test.path] = test.contents;

  if (spec.compute?.target !== undefined) {
    files["README.md"] =
      `${files["README.md"] ?? ""}\n## Compute\n\nCompute target: ${spec.compute.target}. For production, place executions with a\nPlacementDispatcher over a ${spec.compute.target} WorkerRuntime (see @loom/dispatcher).\n`;
  }

  return Object.entries(files).map(([path, contents]) => ({ path, contents }));
}

/**
 * Back-compat alias: generate a whole project. Prefer {@link generateProject} (new
 * app) or {@link generateFlows} (existing app) directly.
 */
export const generateApp = generateProject;
