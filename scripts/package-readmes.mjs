#!/usr/bin/env node
// Generates a short README.md for every workspace package (packages/*, plugins/*, tools/*) that has
// no hand-written one. A generated README starts with GENERATED_MARKER; a README without the marker
// is hand-written and is never overwritten (to take over a generated README, delete its first, marker, line). Regenerate with:  node scripts/package-readmes.mjs
// `--check` exits 1 if any generated README is stale or missing (the spec guard
// `packages/spec/src/packageReadmes.test.ts` runs the same comparison in-process).
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const GENERATED_MARKER =
  "<!-- generated by scripts/package-readmes.mjs from package.json; do not edit - regenerate with `node scripts/package-readmes.mjs`; to hand-write this README instead, delete this line -->";

/** Stable prefix that identifies a generated README even when the marker wording changes. */
const MARKER_PREFIX = "<!-- generated by scripts/package-readmes.mjs";

export const WORKSPACE_DIRS = ["packages", "plugins", "tools"];

/** @returns {{ dir: string, rel: string, pkg: any }[]} every workspace package, sorted by path. */
export function workspacePackages(root) {
  const out = [];
  for (const base of WORKSPACE_DIRS) {
    const baseDir = join(root, base);
    if (!existsSync(baseDir)) continue;
    for (const entry of readdirSync(baseDir).sort()) {
      const file = join(baseDir, entry, "package.json");
      if (!existsSync(file)) continue;
      out.push({
        dir: join(baseDir, entry),
        rel: `${base}/${entry}`,
        pkg: JSON.parse(readFileSync(file, "utf8")),
      });
    }
  }
  return out;
}

/** Org headings of docs/api-reference.org that cover `name` (`** ~@loom/x~ - ...`). */
export function apiReferenceHeading(orgText, name) {
  for (const line of orgText.split("\n")) {
    if (!/^\*+\s/.test(line)) continue;
    if ([...line.matchAll(/~(@[\w-]+\/[\w-]+)~/g)].some((m) => m[1] === name)) {
      return line.replace(/^\*+\s+/, "").replace(/~/g, "`");
    }
  }
  return undefined;
}

function exportTargets(pkg) {
  const ex = pkg.exports;
  if (!ex) return [];
  return Object.keys(ex).map((sub) => (sub === "." ? pkg.name : `${pkg.name}/${sub.slice(2)}`));
}

/** The generated README text for one package. Pure: depends only on its arguments. */
export function renderReadme({ rel, pkg }, apiReferenceOrg) {
  const lines = [GENERATED_MARKER, "", `# ${pkg.name}`, ""];
  lines.push(`${pkg.description}`, "");
  const entries = exportTargets(pkg);
  if (entries.length > 0 || pkg.bin) {
    lines.push("## Entry points", "");
    for (const e of entries) lines.push(`- \`${e}\``);
    if (pkg.bin) {
      const bins = typeof pkg.bin === "string" ? [pkg.name.split("/").pop()] : Object.keys(pkg.bin);
      for (const b of bins) lines.push(`- \`${b}\` (command-line binary)`);
    }
    lines.push("");
  }
  lines.push("## Install", "");
  lines.push(
    pkg.private
      ? "Private workspace package; not published."
      : "Unpublished for now: inside this repo use `workspace:*`; from a sibling checkout use a `link:` override (see [AGENTS.md](../../AGENTS.md)).",
    ""
  );
  const heading = apiReferenceHeading(apiReferenceOrg, pkg.name);
  lines.push("## Status / See also", "");
  if (heading) {
    lines.push(
      `- API reference: section "${heading}" in [docs/api-reference.org](../../docs/api-reference.org).`
    );
  } else {
    lines.push("- Not part of the public API reference (`docs/api-reference.org`).");
  }
  lines.push(
    "- Guides: [docs/user-guide.md](../../docs/user-guide.md), [docs/README.md](../../docs/README.md).",
    `- Source: \`${rel}/src\`.`,
    ""
  );
  return lines.join("\n");
}

/** Pending work: [{ file, text, state }] for every package without a hand-written README. */
export function plan(root) {
  const org = readFileSync(join(root, "docs/api-reference.org"), "utf8");
  const out = [];
  for (const p of workspacePackages(root)) {
    const file = join(p.dir, "README.md");
    const existing = existsSync(file) ? readFileSync(file, "utf8") : undefined;
    if (existing !== undefined && !existing.startsWith(MARKER_PREFIX)) continue; // hand-written
    const text = renderReadme(p, org);
    out.push({
      file,
      text,
      state: existing === undefined ? "missing" : existing === text ? "ok" : "stale",
    });
  }
  return out;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const check = process.argv.includes("--check");
  let bad = 0;
  for (const { file, text, state } of plan(root)) {
    if (state === "ok") continue;
    bad++;
    if (check)
      console.error(
        `${state}: ${relative(root, file)} (run node scripts/package-readmes.mjs; to hand-write it instead, delete its first marker line)`
      );
    else writeFileSync(file, text);
  }
  if (check && bad > 0) process.exit(1);
  if (!check) console.log(`wrote ${bad} README(s)`);
}
